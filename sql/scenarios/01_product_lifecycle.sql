-- ============================================================
-- 01_product_lifecycle.sql
-- Жизненный цикл товара
-- ============================================================

BEGIN;

-- ------------------------------------------------------------
-- Этап 1. Создание нового товара
-- ------------------------------------------------------------

INSERT INTO products (
    category_id,
    sku,
    title,
    description,
    price,
    stock_quantity,
    is_deleted
)
VALUES (
    (SELECT id
     FROM categories
     WHERE name = 'Аксессуары'
     LIMIT 1),

    'TEST-HEADPHONES-001',

    'Тестовые беспроводные наушники',

    'Тестовый товар для проверки жизненного цикла сущности',

    5990.00,

    10,

    FALSE
);


-- ------------------------------------------------------------
-- Этап 2. Изменение характеристик товара
-- Контент-менеджер изменяет цену и описание товара
-- ------------------------------------------------------------

UPDATE products
SET
    price = 6490.00,
    description = 'Беспроводные наушники с Bluetooth и микрофоном'
WHERE sku = 'TEST-HEADPHONES-001'
  AND is_deleted = FALSE;


-- ------------------------------------------------------------
-- Этап 3. Изменение складского остатка
-- ------------------------------------------------------------

UPDATE products
SET stock_quantity = stock_quantity + 5
WHERE sku = 'TEST-HEADPHONES-001'
  AND is_deleted = FALSE;


-- ------------------------------------------------------------
-- Этап 4. Проверка текущего состояния товара
-- ------------------------------------------------------------

SELECT
    id,
    sku,
    title,
    price,
    stock_quantity,
    is_deleted
FROM products
WHERE sku = 'TEST-HEADPHONES-001';


-- ------------------------------------------------------------
-- Этап 5. Мягкое удаление товара
--
-- Физический DELETE не используется.
-- Товар остается в БД, но перестает быть активным.
-- ------------------------------------------------------------

UPDATE products
SET is_deleted = TRUE
WHERE sku = 'TEST-HEADPHONES-001';


-- ------------------------------------------------------------
-- Этап 6. Проверка результата мягкого удаления
-- ------------------------------------------------------------

SELECT
    id,
    sku,
    title,
    is_deleted
FROM products
WHERE sku = 'TEST-HEADPHONES-001';

COMMIT;